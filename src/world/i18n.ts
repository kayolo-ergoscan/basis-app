const bundle = { en, ru } satisfies I18nBundle;
export default bundle;

export type WorldKey = Key;

const plural: Record<Lang, Intl.PluralRules> = { en: new Intl.PluralRules("en"), ru: new Intl.PluralRules("ru") };

/** Raw lookup with RU → EN fallback (undefined when the key is unknown). */
export function worldLookup(key: string, lang: Lang = "en"): string | undefined {
  return (lang === "ru" ? (ru as Record<string, string | undefined>)[key] : undefined) ?? (en as Record<string, string>)[key];
}

export interface WorldTextOptions {
  /**
   * Display name for a participant id. Params that start with "@" are participant ids ("@alice"); by default
   * they render as the town's cast names in `lang` (`world.cast.<id>.name`), else the id itself.
   */
  name?: (id: string) => string | undefined;
}

/** A cast member's display name in `lang` (undefined when the id is not in the town's cast). */
export function castName(id: string, lang: Lang = "en"): string | undefined {
  return worldLookup(`world.cast.${id}.name`, lang);
}

function interp(s: string, params: Record<string, string | number> | undefined, lang: Lang, o: WorldTextOptions): string {
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (m, k: string) => {
    if (!(k in params)) return m;
    const v = String(params[k]);
    if (v.startsWith("@")) {
      const id = v.slice(1);
      return o.name?.(id) ?? castName(id, lang) ?? id;
    }
    if (k === "reason" && v.startsWith("world.")) return worldLookup(v, lang) ?? v;
    return v;
  });
}

/** Renders a `world.` key in `lang` with {param} interpolation (missing keys render as the key). */
export function worldText(key: string, params?: Record<string, string | number>, lang: Lang = "en", o: WorldTextOptions = {}): string {
  const s = worldLookup(key, lang);
  return s === undefined ? key : interp(s, params, lang, o);
}

/** Plural form: key_one / key_few / key_many / key_other, then key; {n} is available. */
export function worldPlural(key: string, n: number, params?: Record<string, string | number>, lang: Lang = "en", o: WorldTextOptions = {}): string {
  const cat = plural[lang].select(n);
  const k = [`${key}_${cat}`, `${key}_other`, key].find((x) => worldLookup(x, lang) !== undefined) ?? key;
  return worldText(k, { n, ...params }, lang, o);
}

